import { useEffect, type ReactNode } from 'react';
import { Platform, StyleSheet, View } from 'react-native';
import { useTheme } from './theme';

/** The app never gets wider than a large phone; on bigger screens it stays a centred column on a plain backdrop. */
const MAX_WIDTH = 520;

function setMeta(name: string, content: string) {
  let el = document.head.querySelector<HTMLMetaElement>(`meta[name="${name}"]`);
  if (!el) {
    el = document.createElement('meta');
    el.name = name;
    document.head.appendChild(el);
  }
  el.content = content;
}

/**
 * Makes the web page behave like an app instead of a document: edge to edge under the iPhone notch,
 * the real visible height (Safari's address bar included), no rubber-band scrolling or tap flashes,
 * and a status bar colour that matches the screen. Done at runtime because the page shell is generated by the build.
 */
function useAppChrome(background: string) {
  useEffect(() => {
    if (Platform.OS !== 'web') return;
    setMeta('viewport', 'width=device-width, initial-scale=1, viewport-fit=cover');
    setMeta('theme-color', background);
    setMeta('mobile-web-app-capable', 'yes');
    setMeta('apple-mobile-web-app-capable', 'yes');
    setMeta('apple-mobile-web-app-status-bar-style', 'default');

    let style = document.getElementById('app-chrome') as HTMLStyleElement | null;
    if (!style) {
      style = document.createElement('style');
      style.id = 'app-chrome';
      document.head.appendChild(style);
    }
    style.textContent = `
      html, body { height: 100%; height: 100dvh; overscroll-behavior: none; -webkit-text-size-adjust: 100%; -webkit-tap-highlight-color: transparent; }
      body { background-color: ${background}; touch-action: manipulation; }
    `;
  }, [background]);
}

/** Web only. Phones get the app full screen; wider windows get a full-height app column. Native renders as is. */
export function AppShell({ children }: { children: ReactNode }) {
  const t = useTheme();
  useAppChrome(t.bg);
  if (Platform.OS !== 'web') return <>{children}</>;
  return (
    <View style={[s.backdrop, { backgroundColor: t.border }]}>
      <View style={[s.app, { backgroundColor: t.bg, borderColor: t.border }]}>{children}</View>
    </View>
  );
}

const s = StyleSheet.create({
  backdrop: { flex: 1, alignItems: 'center' },
  app: { flex: 1, width: '100%', maxWidth: MAX_WIDTH, borderLeftWidth: StyleSheet.hairlineWidth, borderRightWidth: StyleSheet.hairlineWidth, overflow: 'hidden' },
});
